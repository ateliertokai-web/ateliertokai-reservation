/* プライバシーポリシーの文章。事業者名・責任者・窓口・保管期間などは、管理画面「お客様画面」タブの「プライバシーポリシー」で書き換えられる（config/privacy）。
   ※ 一般的なひな型です。公開前に、会社の法務担当（または専門家）が、内容を確認してください */
(function (root) {
  'use strict';
  var DEF = {
    biz: '', addr: '', tel: '', mail: '', resp: '',
    keep: 'イベント終了後1年', date: '', extra: '',
    // 第三者への提供（1行に1件）。イベントの運営のために、開催先・宿泊先などに、お客様の情報をお知らせする場合の、提供先と内容
    provide: 'ゴルフのイベント：ゴルフ場に、参加者のお名前（組み合わせ表・スコアボードの作成のため）\nホテルなどの宿泊を伴うイベント：宿泊先に、お名前・人数・ご連絡先（宿泊の手配のため）'
  };
  function esc(s) { return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); }
  function has(v, k) { return !!(String((v && v[k]) || '').trim() || (k === 'keep' && DEF.keep)); }
  function f(v, k) { var s = String((v && v[k]) || '').trim() || DEF[k]; return s ? esc(s) : '<span class="ph">（管理画面で設定してください）</span>'; }
  // 提供先の一覧（1行に1件）。「なし」とだけ書くと、提供しない旨の文章になる
  function provide(v) {
    var t = String((v && v.provide) || '').trim() || DEF.provide;
    if (/^(なし|ない|無し|提供しない)$/.test(t)) return '<p>現在、イベントの運営のために、開催先・宿泊先などへ、お客様の情報を提供する予定は、ありません。</p>';
    return '<ul>' + t.split(/\r?\n/).map(function (x) { return x.trim(); }).filter(Boolean).map(function (x) { return '<li>' + esc(x) + '</li>'; }).join('') + '</ul>';
  }
  function html(v) {
    v = v || {};
    var ex = String(v.extra || '').trim();
    return '<h1>プライバシーポリシー（個人情報の取り扱いについて）</h1>' +
      (has(v, 'date') ? '<p class="upd">制定・改定日：' + f(v, 'date') + '</p>' : '') +
      '<p>' + f(v, 'biz') + '（以下「当社」）は、この予約システム（予約ページ・お連れ様の入力ページ・アプリ）で、お客様からお預かりする個人情報を、次のとおり、取り扱います。</p>' +
      '<h2>1. 事業者・お問い合わせ窓口</h2>' +
      // 空欄の項目は、表に出さない（事業者名と、お問い合わせの窓口が1つもないときだけ、設定のお願いを出す）
      '<table><tr><th>事業者名</th><td>' + f(v, 'biz') + '</td></tr>' + (has(v, 'addr') ? '<tr><th>住所</th><td>' + f(v, 'addr') + '</td></tr>' : '') + (has(v, 'resp') ? '<tr><th>個人情報の責任者</th><td>' + f(v, 'resp') + '</td></tr>' : '') +
      '<tr><th>お問い合わせ</th><td>' + ((has(v, 'tel') || has(v, 'mail')) ? [has(v, 'tel') ? '電話：' + f(v, 'tel') : '', has(v, 'mail') ? 'メール：' + f(v, 'mail') : ''].filter(Boolean).join('<br>') : '<span class="ph">（管理画面で設定してください）</span>') + '</td></tr></table>' +
      '<h2>2. お預かりする情報</h2><ul><li>お名前（ご予約の代表者様、参加者様、お連れ様）、法人名</li><li>連絡先（電話番号）、メールアドレス</li>' +
      '<li>保有車両の登録ナンバー・車種（またはご注文中・新規のお申し出）、オーナーズカードID、ご利用店舗・担当スタッフ</li>' +
      '<li>ゴルフのイベント：参加者のお名前、レクサスオーナーかどうか、お連れ様がご自身で入力されたお名前・メールアドレス</li>' +
      '<li>備考欄にご入力いただいた内容、ご予約の状況（確定・キャンセル待ち・抽選結果など）</li>' +
      '<li>通知をお受け取りになる場合：お使いの端末の通知の宛先（端末を特定する符号）と、ご予約番号の対応</li></ul>' +
      '<h2>3. 利用目的</h2><ul><li>ご予約・お申し込みの受付、確認、変更、キャンセルの手続き</li><li>抽選、キャンセル待ちからの繰り上げ、その結果のご連絡</li>' +
      '<li>イベントのご案内、当日の運営（受付、組み合わせ表の作成、成績表・記念写真のご案内、スコアボードの送信）</li>' +
      '<li>店舗からの、ご予約に関するご連絡（電話、メール、アプリの通知）</li><li>システムの安全な運用（不正なお申し込みの防止、障害の調査、バックアップ）</li></ul>' +
      '<p>上記の目的の範囲を超えて、利用することはありません。</p>' +
      '<h2>4. 第三者への提供・委託</h2><p>法令に基づく場合を除き、ご本人の同意なく、第三者に個人情報を提供しません。ただし、このシステムの運営のため、次のサービスに、データの保管・処理を委託しています。</p>' +
      '<ul><li>Google LLC のクラウドサービス（Firebase：データの保管・ログイン・通知の配信／Google ドライブ・Apps Script：バックアップと、メール・通知の自動送信）。データは、同社の管理する国内外のサーバーで保管されることがあります。</li>' +
      '<li>画面の配信：GitHub（画面のファイルのみ。個人情報は置きません）</li></ul>' +
      '<p>ご予約・お申し込みいただいたイベントの運営のために必要な範囲で、次のとおり、開催先・宿泊先などに、お客様の情報をお知らせすることがあります（イベントごとに、提供の有無は異なります。お申し込みいただくことで、ご同意いただいたものとして、取り扱います）。</p>' + provide(v) +
      '<h2>5. お使いの端末に保存する情報</h2><p>予約ページは、ご予約番号の記録、通知の登録、届いたお知らせを、お使いの端末（ブラウザ）の中に保存します。広告や、閲覧の追跡のための利用は、していません。端末の設定（サイトデータの削除、通知の許可の取り消し）で、いつでも、削除・停止できます。</p>' +
      '<h2>6. 通知（プッシュ通知・メール）</h2><p>通知は、お客様が許可された場合にだけ、お送りします。キャンセル待ちの繰り上げ、抽選の結果、前日のご案内、店舗からのお知らせが、届きます。通知は、端末の設定で、いつでも止められます。メールは、ご予約のときにメールアドレスをご入力いただいた方にだけ、お送りします。</p>' +
      '<h2>7. 保管期間</h2><p>' + f(v, 'keep') + '。期間が過ぎた個人情報は、遅滞なく、削除します（バックアップを含む）。記念写真・成績表は、掲載期間が過ぎると、閲覧できなくなり、削除します。</p>' +
      '<h2>8. 安全管理</h2><p>データは、アクセス権限を限定して保管しています。管理画面に入れるのは、当社が登録したスタッフだけで、ログインには、本人確認を行っています。お客様ご自身のご予約の情報は、ご予約番号（と、メールアドレス）を知る方だけが、見られます。ご予約番号やURLは、他の方に、送らないでください。</p>' +
      '<h2>9. 開示・訂正・利用停止・削除のご請求</h2><p>ご本人から、保有する個人情報の、開示・訂正・利用停止・削除のご請求があった場合は、ご本人であることを確認のうえ、法令に従って、対応します。「1. 事業者・お問い合わせ窓口」まで、ご連絡ください。</p>' +
      '<p><b>保管期間（' + f(v, 'keep') + '）を待たずに、お客様の情報の削除をご希望の場合</b>は、このページの下の「<a href="#delete">お客様情報の削除のご依頼</a>」から、お申し込みください。</p>' +
      '<h2>10. 改定</h2><p>この内容は、法令の改正や、システムの変更に合わせて、改定することがあります。改定した場合は、このページで、お知らせします。</p>' +
      (ex ? '<h2>11. その他</h2><p>' + esc(ex).replace(/\n/g, '<br>') + '</p>' : '');
  }
  root.PRIVACY = { html: html, DEF: DEF };
})(window);
